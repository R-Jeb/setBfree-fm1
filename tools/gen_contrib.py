"""Writes firmware/src/organ_contrib.h from data/setbfree-contrib.txt (made by tools/dump_contrib.c).

For every key (C2..C7) and drawbar bus the list of tonewheels that reach the bus with their gain: the main
wheel (with setBfree's tapering, -10..+7 dB by key and drawbar) and the leakage / crosstalk of the neighbours
(setBfree's default model: compartment, terminal strip and wiring, about -34..-46 dB). Entries weaker than
THR (-46 dB) are left out: they cost a wheel each and cannot be heard. Gains are Q12 (4096 = 1.0).
"""
import pathlib, collections

THR = 0.005
rows = [l.split() for l in pathlib.Path("data/setbfree-contrib.txt").read_text().splitlines()[1:]]
by = collections.defaultdict(list)
for k, b, w, g in rows:
    by[(int(k), int(b))].append((int(w) - 1, float(g)))

idx, ws, gs, main = [], [], [], []
for k in range(61):
    for b in range(9):
        lst = sorted(by[(k, b)], key=lambda e: -e[1])
        main.append(lst[0][0])
        idx.append(len(ws))
        for w, g in lst:
            if g >= THR:
                assert 0 <= w < 91
                ws.append(w)
                gs.append(round(g * 4096))
idx.append(len(ws))
assert max(gs) < 65536 and len(ws) < 65536

def arr(name, ctype, vals, per):
    s = ["static const %s %s[%d] = {" % (ctype, name, len(vals))]
    s += ["    " + ", ".join(str(v) for v in vals[i:i + per]) + "," for i in range(0, len(vals), per)]
    return s + ["};", ""]

out = ["/* SPDX-License-Identifier: GPL-2.0-or-later */",
       "/* Generated by tools/gen_contrib.py from setBfree's key contribution matrix: do not edit. */", ""]
out += arr("CT_IDX", "uint16_t", idx, 16)     # entries of (key k, bus b): CT_IDX[k * 9 + b] .. CT_IDX[k * 9 + b + 1]
out += arr("CT_W", "uint8_t", ws, 24)         # wheel 0..90
out += arr("CT_G", "uint16_t", gs, 16)        # gain, Q12
out += arr("CT_MAIN", "uint8_t", main, 27)    # the strongest wheel of (key, bus): percussion takes the 4' / 2 2/3' ones
pathlib.Path("firmware/src/organ_contrib.h").write_text("\n".join(out))
print("%d entries (%.1f per key and bus), %d bytes" % (len(ws), len(ws) / 549, len(ws) * 3 + len(idx) * 2 + 549))

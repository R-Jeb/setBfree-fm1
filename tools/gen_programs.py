"""Writes firmware/src/organ_pgm.h from setBfree's default.pgm (data/setbfree-default.pgm, GPL-2.0-or-later).

Same rules as setBfree's program.c: a later definition of a program number replaces an earlier one, except a run of
definitions with the same number directly after each other, which merge. A program only sets the properties it
names. This organ has one manual: lower-manual / pedal drawbars, key splits, reverb and the lower vibrato switch
are read but have no effect (the program is still kept, so a MIDI program change selects it as in setBfree).
  tools/gen_programs.py [path/to/default.pgm]
"""
import pathlib, re, sys

SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "data/setbfree-default.pgm")
OUT = pathlib.Path("firmware/src/organ_pgm.h")

text = "\n".join(l.split("#", 1)[0] for l in SRC.read_text().splitlines())
blocks = re.findall(r"(\d+)\s*\{(.*?)\}", text, re.S)

def split_assign(body):
    out, cur, q = [], "", False
    for ch in body:
        if ch == '"': q = not q
        if ch == "," and not q:
            out.append(cur); cur = ""
        else:
            cur += ch
    out.append(cur)
    return [a.strip() for a in out if a.strip()]

def digits(v):                                  # as setBfree's parseDrawbarRegistration: the first nine digits count
    d = []
    for c in v:                                 # (program 1 has ten, "888 0000 000": the tenth is ignored)
        if len(d) == 9: break
        if c in " -_": continue
        assert "0" <= c <= "8", v
        d.append(int(c))
    assert len(d) == 9, v
    return d

VIB = {"v1": 0, "c1": 1, "v2": 2, "c2": 3, "v3": 4, "c3": 5}      # setBfree's vibrato knob positions
ROT = {"stop": 0, "chorale": 1, "tremolo": 2}                     # this organ: 0 stop, 1 slow, 2 fast
onoff = lambda v: 1 if v.lower() in ("on", "1", "true") else 0

progs, last = {}, None
for num, body in blocks:
    n = int(num)
    p = progs[n] if (last == n and n in progs) else {"name": "", "set": {}}
    for a in split_assign(body):
        k, v = [s.strip() for s in a.split("=", 1)]
        v = v.strip('"')
        k = k.lower()
        if k == "name": p["name"] = v
        elif k in ("drawbars", "drawbarsupper"):
            if v.lower() == "random": p["set"]["db"] = "random"
            else: p["set"]["db"] = digits(v)
        elif k == "perc": p["set"]["perc"] = onoff(v)
        elif k == "percvol": p["set"]["pvol"] = 1 if v.lower() == "soft" else 0
        elif k == "percspeed": p["set"]["pspd"] = 1 if v.lower() == "fast" else 0
        elif k == "percharm": p["set"]["pharm"] = 1 if v.lower() == "3rd" else 0     # 1 = 3rd (this organ's perc3)
        elif k == "vibrato": p["set"]["vib"] = VIB[v.lower()]
        elif k == "vibratoupper": p["set"]["vup"] = onoff(v)
        elif k == "overdrive": p["set"]["od"] = onoff(v)
        elif k == "rotaryspeed": p["set"]["rot"] = ROT[v.lower()]
        elif k in ("drawbarslower", "drawbarspedals", "vibratolower", "reverbmix", "keysplitpedals",
                   "keysplitlower", "trssplitpedals", "trssplitlower", "trssplitupper"):
            p.setdefault("ignored", []).append(k)
        else:
            raise SystemExit(f"program {n}: unknown property {k!r}")
    progs[n] = p
    last = n

F = {"db": 1, "perc": 2, "pvol": 4, "pspd": 8, "pharm": 16, "vib": 32, "vup": 64, "od": 128, "rot": 256, "rnd": 512}
lines = ["/* SPDX-License-Identifier: GPL-2.0-or-later */",
         "/* Generated by tools/gen_programs.py from setBfree's default.pgm (data/setbfree-default.pgm): do not edit.",
         " * Program numbers as in setBfree (MIDI program change n selects program n + 1). */", "",
         "#define PGM_DB 1u", "#define PGM_PERC 2u", "#define PGM_PVOL 4u", "#define PGM_PSPD 8u", "#define PGM_PHARM 16u",
         "#define PGM_VIB 32u", "#define PGM_VUP 64u", "#define PGM_OD 128u", "#define PGM_ROT 256u", "#define PGM_RND 512u",
         "typedef struct {",
         "    uint16_t set;                               /* PGM_*: the properties this program sets */",
         "    uint8_t db[9], perc, pvol, pspd, pharm, vib, vup, od, rot;",
         "    const char *name;                           /* 0: no such program */",
         "} organ_pgm_t;", "",
         "static const organ_pgm_t PGM[128] = {"]
usable = 0
for n in range(128):
    p = progs.get(n)
    if not p:
        lines.append(f"    [{n}] = {{0}},")
        continue
    s, flags = p["set"], 0
    db = [0] * 9
    for key in s:
        flags |= F["rnd"] if (key == "db" and s[key] == "random") else F[key]
    if isinstance(s.get("db"), list): db = s["db"]
    if flags: usable += 1
    name = p["name"].replace("\\", "\\\\").replace('"', '\\"')
    assert len(name) <= 28, name
    lines.append("    [%d] = {%du, {%s}, %d, %d, %d, %d, %d, %d, %d, %d, \"%s\"}," % (
        n, flags, ",".join(map(str, db)), s.get("perc", 0), s.get("pvol", 0), s.get("pspd", 0), s.get("pharm", 0),
        s.get("vib", 0), s.get("vup", 0), s.get("od", 0), s.get("rot", 0), name))
lines.append("};")
OUT.write_text("\n".join(lines) + "\n")
reg = [n for n, p in sorted(progs.items()) if "db" in p["set"]]
print(f"{len(progs)} programs, {usable} with an effect on one manual, {len(reg)} registrations:", reg)

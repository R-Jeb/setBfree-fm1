"""Writes firmware/src/organ_leslie.h from data/setbfree-whirl.txt (made by tools/dump_whirl.c from setBfree's
b_whirl/whirl.c, 44.1 kHz), plus the speeds and the reverb's delay lengths (b_reverb/reverb.c).

  LES_HN_FWD / _BWD, LES_DR_FWD / _BWD  1024 entries, delay of the sound by the rotor's angle, Q8 samples (Q4 left a noise: the delay moved in steps of 1/16 sample)
  LES_BFW / LES_BBW                     1024 x 5, the horn's angle-dependent filter, Q15
  LES_HSP / LES_DSP, LES_HPH / LES_DPH  the six path delays (Q8 samples) and phase offsets (of 2^32) of horn and drum
  LES_HA / LES_HB / LES_DF              biquads, Q28: b0 b1 b2 a1 a2
  LES_*_RATE, LES_*_ACC/DEC             speeds (phase step per frame) and the acceleration, per 256-frame block (Q16)
  RV_LEN                                the reverb's seven delay lengths
"""
import math, pathlib

FS = 44100
BLOCK = 256
lines = pathlib.Path("data/setbfree-whirl.txt").read_text().splitlines()
kv, rows = {}, []
for ln in lines:
    p = ln.split()
    if p[0] == "t":
        rows.append([float(v) for v in p[2:]])
    else:
        kv[p[0]] = p[1:]
assert len(rows) == 1024

def arr(name, ctype, vals, per, fmt="%d"):
    s = ["static const %s %s[%d] = {" % (ctype, name, len(vals))]
    s += ["    " + ", ".join(fmt % v for v in vals[i:i + per]) + "," for i in range(0, len(vals), per)]
    return s + ["};", ""]

def col(c, scale):
    return [round(r[c] * scale) for r in rows]

out = ["/* SPDX-License-Identifier: GPL-2.0-or-later */",
       "/* Generated by tools/gen_leslie.py from setBfree's Leslie (b_whirl/whirl.c): do not edit. */", ""]
assert max(max(col(c, 256)) for c in range(4)) < 65536, "a delay does not fit Q8 in 16 bits"
out += arr("LES_HN_FWD", "uint16_t", col(0, 256), 16)
out += arr("LES_HN_BWD", "uint16_t", col(1, 256), 16)
out += arr("LES_DR_FWD", "uint16_t", col(2, 256), 16)
out += arr("LES_DR_BWD", "uint16_t", col(3, 256), 16)
bfw = [v for r in rows for v in [round(x * 32768) for x in r[4:9]]]
bbw = [v for r in rows for v in [round(x * 32768) for x in r[9:14]]]
assert max(abs(v) for v in bfw + bbw) < 32768
out += arr("LES_BFW", "int16_t", bfw, 20)
out += arr("LES_BBW", "int16_t", bbw, 20)
out += arr("LES_HSP", "uint32_t", [round(float(v) * 256) for v in kv["hornSpacing"]], 6)
out += arr("LES_DSP", "uint32_t", [round(float(v) * 256) for v in kv["drumSpacing"]], 6)
out += arr("LES_HPH", "uint32_t", [int(v) << 18 for v in kv["hornPhase"]], 6, "%du")
out += arr("LES_DPH", "uint32_t", [int(v) << 18 for v in kv["drumPhase"]], 6, "%du")

def q28(name, key):
    v = [float(x) for x in kv[key]]                 # a0 a1 a2 b0 b1 b2 z0 z1 (setBfree's order)
    c = [v[3], v[4], v[5], v[1], v[2]]               # b0 b1 b2 a1 a2
    assert max(abs(x) for x in c) < 2.0
    return arr(name, "int32_t", [round(x * 2 ** 28) for x in c], 5)
out += q28("LES_HA", "hafw") + q28("LES_HB", "hbfw") + q28("LES_DF", "drfL")
out.append("#define LES_HORN_LEVEL %d                  /* 0.7, Q15 */" % round(0.7 * 32768))
out.append("#define LES_LEAK %d                        /* 0.15 * 0.7, Q15: the filtered input on both channels */" % round(0.105 * 32768))

def inc(f):
    return round(f * 2 ** 32 / FS)
out.append("#define LES_HORN_SLOW %du                  /* 0.672 Hz: phase step per frame */" % inc(0.672))
out.append("#define LES_HORN_FAST %du                  /* 7.056 Hz */" % inc(7.056))
out.append("#define LES_DRUM_SLOW %du                  /* 0.600 Hz */" % inc(0.600))
out.append("#define LES_DRUM_FAST %du                  /* 5.955 Hz */" % inc(5.955))
bps = FS / BLOCK
def k(tc):                                           # 1 - exp(-1 / (blocks per second * time constant)), Q16
    return round((1 - math.exp(-1 / (bps * tc))) * 65536)
out.append("#define LES_HORN_ACC %d                    /* time constants 0.161 s, 0.321 s; drum 4.127 s, 1.371 s (setBfree) */" % k(0.161))
out.append("#define LES_HORN_DEC %d" % k(0.321))
out.append("#define LES_DRUM_ACC %d" % k(4.127))
out.append("#define LES_DRUM_DEC %d" % k(1.371))
out.append("")
rv = [(e * 2) | 1 for e in (2999, 2331, 1893, 1097, 1051, 337, 113)]   # b_reverb: end * rate / 22050, | 1; the line is e + 1 long
lens = [e + 1 for e in rv]
out += arr("RV_LEN", "uint16_t", lens, 7)
offs = [sum(lens[:i]) for i in range(8)]
out += arr("RV_OFF", "uint16_t", offs, 8)
out.append("#define RV_TOTAL %d" % offs[7])
pathlib.Path("firmware/src/organ_leslie.h").write_text("\n".join(out))
print("rv total", sum(lens), "samples; horn acc/dec", k(0.161), k(0.321), "drum", k(4.127), k(1.371))
